import { test, expect } from '@playwright/test'
import { fixture } from './forecast-order-fixture'
import { openHeaderMenu } from './header-navigation'

test.use({ hasTouch: true })
for (const width of [320, 360, 390, 430, 640, 641, 768, 1440]) for (const lang of ['bg', 'en'] as const) for (const dark of [false, true]) {
  test(`Windy ${width} ${lang} ${dark}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.clock.setFixedTime(new Date('2026-10-13T08:00:00Z'))
    await fixture(page, lang)
    let loads = 0
    await page.route('https://embed.windy.com/**', route => {
      loads++
      return route.fulfill({ contentType: 'text/html', body: '<body style="margin:0;background:#b8d6e9"><button style="margin:20px">Synthetic map control</button></body>' })
    })
    // Reload to install a stable cross-origin map fixture; no Windy DOM access.
    await page.reload()
    await expect(page.locator('.main-card .big-temp')).toBeVisible()
    if (dark) {
      await openHeaderMenu(page)
      await page.locator('.header-menu > .icon-btn').click()
      if (width <= 640) await page.locator('.mobile-menu-toggle').click()
    }
    await page.addStyleTag({ content: '*, *::before, *::after { animation:none!important; transition:none!important }' })
    const map = page.locator('.map-section'), frame = map.locator('iframe')
    await map.scrollIntoViewIfNeeded()
    await expect(frame).toBeVisible()
    await expect.poll(() => loads).toBe(1)
    const src = await frame.getAttribute('src')
    const original = await frame.elementHandle()
    const params = new URL(src!).searchParams
    expect(params.get('overlay')).toBe('rain')
    expect(params.get('metricRain')).toBe('mm')
    expect(params.get('metricTemp')).toBe('°C')
    expect(params.get('metricWind')).toBe('km/h')
    const full = map.getByRole('button', { name: lang === 'bg' ? 'На цял екран' : 'Fullscreen', exact: true })
    if (width <= 640) {
      expect((await frame.boundingBox())!.height).toBe(320)
      await expect(frame).toHaveAttribute('tabindex', '-1')
      expect(await frame.evaluate(e => getComputedStyle(e).pointerEvents)).toBe('none')
      const shield = map.locator('.windy-scroll-shield')
      expect(await shield.evaluate(e => getComputedStyle(e).touchAction)).toBe('pan-y')
      const y = await page.evaluate(() => scrollY)
      await shield.hover(); await page.mouse.wheel(0, 150)
      await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(y)
      const interact = map.getByRole('button', { name: lang === 'bg' ? 'Управлявай картата' : 'Interact with map', exact: true })
      await interact.click()
      await expect(map.locator('[aria-pressed=true]')).toBeVisible()
      expect(await frame.evaluate(e => getComputedStyle(e).pointerEvents)).toBe('auto')
      await map.getByRole('button', { name: lang === 'bg' ? 'Върни превъртането' : 'Return to scrolling', exact: true }).click()
      expect(await frame.evaluate(e => getComputedStyle(e).pointerEvents)).toBe('none')
      await full.click()
      const close = map.getByRole('button', { name: lang === 'bg' ? 'Затвори' : 'Close', exact: true })
      await expect(close).toBeFocused()
      await expect(map.getByRole('dialog')).toBeVisible()
      expect(await page.evaluate(() => document.fullscreenElement)).toBeNull()
      expect(await page.evaluate(() => document.body.style.position)).toBe('fixed')
      expect((await map.locator('dialog').boundingBox())!.height).toBe(900)
      await expect(map.locator('dialog')).toHaveScreenshot(`${width}-${lang}-${dark}-fullscreen.png`, { animations: 'disabled' })
      await page.setViewportSize({ width: 900, height: width })
      await expect(close).toBeVisible()
      const box = (await close.boundingBox())!
      expect(box.y).toBeGreaterThanOrEqual(0); expect(box.y + box.height).toBeLessThanOrEqual(width)
      await expect(map.locator('dialog')).toHaveScreenshot(`${width}-${lang}-${dark}-landscape.png`, { animations: 'disabled' })
      await page.setViewportSize({ width, height: 900 })
      await close.click()
      await expect(full).toBeFocused()
      await full.click(); await page.keyboard.press('Escape')
      await expect(full).toBeFocused()
      expect(await page.evaluate(() => document.body.style.position)).toBe('')
    } else {
      await expect(full).toBeHidden()
      expect((await frame.boundingBox())!.height).toBe(width <= 760 ? 430 : width === 768 ? 420 : 620)
      expect(await frame.evaluate(e => getComputedStyle(e).pointerEvents)).toBe('auto')
    }
    expect(await frame.evaluate((e, old) => e === old, original)).toBe(true)
    await expect(frame).toHaveAttribute('src', src!)
    expect(loads).toBe(1)
    await map.scrollIntoViewIfNeeded()
    await expect(map).toHaveScreenshot(`${width}-${lang}-${dark}.png`, { animations: 'disabled' })
  })
}

test('touch scrolling, modal keyboard containment and selected city', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.clock.setFixedTime(new Date('2026-10-13T08:00:00Z'))
  await fixture(page)
  await page.route('https://embed.windy.com/**', route => route.fulfill({ contentType: 'text/html', body: '<button>Map fixture</button>' }))
  await page.locator('.city-btn').filter({ hasText: 'Варна' }).click()
  const frame = page.locator('.map-section iframe')
  await expect(frame).toHaveAttribute('src', /lat=43\.2141&lon=27\.9147/)
  const src = await frame.getAttribute('src')
  const map = page.locator('.map-section')
  await map.scrollIntoViewIfNeeded()
  const shield = (await map.locator('.windy-scroll-shield').boundingBox())!
  const initial = await page.evaluate(() => scrollY)
  const session = await page.context().newCDPSession(page)
  const x = shield.x + shield.width / 2, y = shield.y + shield.height * .8
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
  for (let step = 1; step <= 8; step++) await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y - step * 20 }] })
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(initial)
  await session.detach()
  await map.getByRole('button', { name: 'На цял екран', exact: true }).click()
  const close = map.getByRole('button', { name: 'Затвори', exact: true })
  await expect(close).toBeFocused()
  expect(await map.locator('dialog').evaluate(element => element.matches(':modal'))).toBe(true)
  await page.locator('.city-btn.active').evaluate(element => (element as HTMLElement).focus())
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  expect(await page.evaluate(() => document.querySelector('.windy-view')!.contains(document.activeElement))).toBe(true)
  await close.click()
  await expect(frame).toHaveAttribute('src', src!)
  await expect(page.locator('.city-btn.active')).toContainText('Варна')
  await map.getByRole('button', { name: 'На цял екран', exact: true }).click()
  await page.setViewportSize({ width: 900, height: 390 })
  await close.click()
  await expect(frame).toBeFocused()
  await expect(frame).toHaveAttribute('src', src!)
})
